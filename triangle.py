def area(a, h):
    """Вычисляет площадь треугольника по основанию и высоте.

    Параметры: a (int или float) - сторона;
               h (int или float) - высота.
    Возвращает: площадь (float), S = a * h / 2.

    Пример вызова:
    area(4, 3)
    6.0
    """
    return a * h / 2


def perimeter(a, b, c):
    """Вычисляет периметр треугольника по трём сторонам.

    Параметры: a, b, c (int или float) - 3 стороны.
    Возвращает: периметр (int или float), P = a + b + c.

    Пример вызова:
    perimeter(3, 4, 5)
    12
    """
    return a + b + c
