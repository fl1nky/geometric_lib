def area(a, b):
    """Вычисляет площадь прямоугольника по двум сторонам.

    Параметры: a, b (int или float) - стороны.
    Возвращает: площадь (int или float), S = a * b.

    Пример вызова:
    area(4, 3)
    12
    """
    return a * b


def perimeter(a, b):
    """Вычисляет периметр прямоугольника по двум сторонам.

    Параметры: a, b (int или float) - стороны.
    Возвращает: периметр (int или float), P = 2 * (a + b).

    Пример вызова:
    perimeter(4, 3)
    14
    """
    return 2 * (a + b)
