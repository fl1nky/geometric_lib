
def area(a):
    """Вычисляет площадь квадрата по стороне a.

    Параметр: a (int или float) - сторона.
    Возвращает: площадь (int или float), S = a * a.

    Пример вызова:
    area(4)
    16
    """
    return a * a


def perimeter(a):
    """Вычисляет периметр квадрата по стороне a.

    Параметр: a (int или float) - сторона.
    Возвращает: периметр (int или float), P = 4 * a.

    Пример вызова:
    perimeter(4)
    16
    """
    return 4 * a
